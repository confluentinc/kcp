package main

import (
	"strings"
	"testing"
)

func rules(fs []Finding) string {
	var out []string
	for _, f := range fs {
		out = append(out, f.Rule)
	}
	return strings.Join(out, ",")
}

func TestLint(t *testing.T) {
	tests := []struct {
		name string
		src  string
		want string
	}{
		{"one line ok", "package p\n// Does a thing.\nfunc Foo() {}", ""},
		{"no comment ok", "package p\nfunc Foo() {}", ""},
		{"two lines warn", "package p\n// Does\n// a thing.\nfunc Foo() {}", "multi-line"},
		{"three lines warn", "package p\n// a\n// b\n// c\nfunc Foo() {}", "multi-line"},
		{"four lines fail", "package p\n// a\n// b\n// c\n// d\nfunc Foo() {}", "too-long"},
		{"paragraph break not counted", "package p\n// Does.\n//\n// More.\nfunc Foo() {}", "multi-line"},
		{"block comment", "package p\n/* a\n b\n c\n d */\nfunc Foo() {}", "too-long"},
		{"inline", "package p\nfunc Foo() {\n\t// a\n\t// b\n\t_ = 1\n}", "multi-line"},
		{"package doc", "// Package p\n// does things.\npackage p", "multi-line"},
		{"too wide", "package p\n// " + strings.Repeat("x", 101) + "\nfunc Foo() {}", "too-wide"},
		{"process ref", "package p\n// Scoped per the task-4 brief.\nfunc Foo() {}", "process-ref"},
		{"banner", "package p\n// ------\n// Data flow: produce, mirror, consume\n// ------\nfunc TestX() {}", "banner"},
		{"bare rule", "package p\n// =========\nfunc Foo() {}", "banner"},
		{"box-drawing banner", "package p\n// ── stub ─────────\nfunc Foo() {}", "banner"},
		{"one-line section header ok", "package p\n// --- error paths: bad combinations fail fast ---\nfunc Foo() {}", ""},
		{"width counts characters", "package p\n// " + strings.Repeat("─", 60) + "x\nfunc Foo() {}", "banner"},
		{"label alone ok", "package p\n// Data flow: produce, mirror, consume\nfunc TestX() {}", ""},
		{"plan section", "package p\n// --- drift check (§13) ---\nfunc Foo() {}", "process-ref"},
		{"requirement id", "package p\n// R3/R6: legacy value rejected.\nfunc Foo() {}", "process-ref"},
		{"acceptance example id", "package p\n// Overwritten on purpose (AE4).\nfunc Foo() {}", "process-ref"},
		{"review ticket", "package p\n// Must reject (cfet1 #6205997094).\nfunc Foo() {}", "process-ref"},
		{"history is a warning", "package p\n// Previously returned nil.\nfunc Foo() {}", "history"},
		{"single capital word ok", "package p\n// Must NOT be called twice.\nfunc Foo() {}", ""},
		{"repeated emphasis", "package p\n// Runs BEFORE Bar, NEVER after.\nfunc Foo() {}", "emphasis"},
		{"directives ignored", "package p\n//go:generate stringer -type=T\n//nolint:errcheck\nfunc Foo() {}", ""},
		{"directive plus one line ok", "package p\n// Does a thing.\n//go:noinline\nfunc Foo() {}", ""},
		{"generated file skipped", "// Code generated by x. DO NOT EDIT.\n\npackage p\n// task-1 a\n// b\nfunc Foo() {}", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			fs, err := Lint("x.go", []byte(tt.src), nil, DefaultLimits)
			if err != nil {
				t.Fatal(err)
			}
			if got := rules(fs); got != tt.want {
				t.Errorf("got %q, want %q", got, tt.want)
			}
		})
	}
}

func TestLintRestatesName(t *testing.T) {
	tests := []struct {
		name, file, src, want string
	}{
		{"exported func ok", "x.go", "package p\n// Foo does a thing.\nfunc Foo() {}", ""},
		{"exported type ok", "x.go", "package p\n// T holds x.\ntype T struct{}", ""},
		{"unexported func", "x.go", "package p\n// foo does a thing.\nfunc foo() {}", "restates-name"},
		{"unexported type", "x.go", "package p\n// t holds x.\ntype t struct{}", "restates-name"},
		{"test func", "x_test.go", "package p\n// TestFoo checks foo.\nfunc TestFoo(t *testing.T) {}", "restates-name"},
		{"exported helper in test file", "x_test.go", "package p\n// Helper builds x.\nfunc Helper() {}", "restates-name"},
		{"no name ok", "x.go", "package p\n// Does a thing.\nfunc foo() {}", ""},
		{"name later ok", "x.go", "package p\n// Wraps foo for retries.\nfunc foo() {}", ""},
		{"prefix of longer word ok", "x.go", "package p\n// fooish behaviour.\nfunc foo() {}", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			fs, _ := Lint(tt.file, []byte(tt.src), nil, DefaultLimits)
			if got := rules(fs); got != tt.want {
				t.Errorf("got %q, want %q", got, tt.want)
			}
		})
	}
}

func TestLintOnlyChangedLines(t *testing.T) {
	src := `package p
// a task-1 comment
func Foo() {}

// another task-2 comment
func Bar() {}`
	fs, err := Lint("x.go", []byte(src), map[int]bool{5: true}, DefaultLimits)
	if err != nil {
		t.Fatal(err)
	}
	if len(fs) != 1 || fs[0].Line != 5 {
		t.Fatalf("want one finding on line 5, got %+v", fs)
	}
}

func TestWarningsAreFlagged(t *testing.T) {
	fs, _ := Lint("x.go", []byte("package p\n// Previously ran twice.\nfunc Foo() {}"), nil, DefaultLimits)
	if len(fs) != 1 || !fs[0].Warn {
		t.Fatalf("want one warning, got %+v", fs)
	}
}

func TestSameCode(t *testing.T) {
	base := "package p\n\n// Foo does x\n// at length.\nfunc Foo() int { return 1 } // trailing\n"
	tests := []struct {
		name string
		src  string
		want bool
	}{
		{"comment removed", "package p\n\nfunc Foo() int { return 1 }\n", true},
		{"comment reworded", "package p\n\n// Foo does x.\nfunc Foo() int { return 1 }\n", true},
		{"reformatted", "package p\nfunc Foo() int {\n\treturn 1\n}\n", true},
		{"code changed", "package p\n\nfunc Foo() int { return 2 }\n", false},
		{"string changed", "package p\n\nfunc Foo() string { return \"// x\" }\n", false},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := SameCode([]byte(base), []byte(tt.src)); got != tt.want {
				t.Errorf("got %v, want %v", got, tt.want)
			}
		})
	}
}
